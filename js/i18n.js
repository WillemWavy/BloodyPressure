const dicts = { nl, en };
let current = 'en';

export function resolveLang(setting) {
  if (setting === 'nl' || setting === 'en') return setting;
  const langs = navigator.languages && navigator.languages.length ? navigator.languages : [navigator.language || 'en'];
  return langs.some(l => String(l).toLowerCase().startsWith('nl')) ? 'nl' : 'en';
}

export function setLang(lang) {
  current = dicts[lang] ? lang : 'en';
  document.documentElement.lang = current;
}

export function lang() {
  return current;
}

export function locale() {
  return current === 'nl' ? 'nl-NL' : 'en-GB';
}

export const t = new Proxy({}, { get: (_, key) => dicts[current][key] });

export function fmtNum(n, digits = 1) {
  if (n === null || n === undefined || Number.isNaN(n)) return '';
  return new Intl.NumberFormat(locale(), { maximumFractionDigits: digits }).format(n);
}
